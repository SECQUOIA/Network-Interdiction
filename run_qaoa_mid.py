"""
Run the penalty QAOA on the mid-size instances (results/mid_instances.csv,
39-149 qubits) with matrix-product-state simulation, and write one CSV row
per (instance, B, depth, angle source). Issues #1, #16, #17.

Statevector simulation stops near 30 qubits, so these rows are simulated
with Aer's matrix product state, bond dimension capped (--bond-dimension,
32 by default): approximate, and recorded per row. At 116 qubits and p = 1
one expectation value takes about 15 s at a cap of 32 and 90 s at 64, and
the two differ by 0.01 in gap_closed, so training angles here costs tens
of minutes per row at p = 1 and is impractical beyond. Angles come instead
from a source:

    donor   the angles trained on tiny_a B = 1 at the same depth
            (results/qaoa_tiny.csv), reused unchanged: the parameter-transfer
            baseline of #16
    train   COBYLA from the linear ramp on the MPS expectation itself, for
            rows of at most --train-max-qubits qubits; what transfer is
            measured against

Every row is scored from shots (qaoa_common.score_samples) and by
gap_closed, the share of the energy gap between the uniform state (0) and
the ground state (1) that the state's expected energy closes; the ground
energy is Gurobi's (needs a license).

Columns: instance, family, B, qubits, reps, angles, bond_dimension, theta,
evaluations, train_time_sec, expected_energy, gap_closed, shot_p_optimal,
p_feasible, shot_mean_ratio, best_sample_energy, flow_before_repair,
flow_after_repair, opt_nip, greedy, maxflow, ground_energy, offset,
sample_time_sec.

    python run_qaoa_mid.py --reps 1,2,3 --angles donor,train \\
        --out results/qaoa_mid.csv
"""
import argparse
import csv
import json
import math
from importlib.metadata import version
import os
import sys

import pandas as pd

import qaoa_common as qc
import run_benchmark as rb

MANIFEST = os.path.join('results', 'mid_instances.csv')
TINY_CSV = os.path.join('results', 'qaoa_tiny.csv')
ANGLE_SOURCES = ('donor', 'train')
COLUMNS = ['instance', 'family', 'B', 'qubits', 'reps', 'angles',
           'bond_dimension', 'theta', 'evaluations', 'train_time_sec',
           'expected_energy', 'gap_closed', 'shot_p_optimal', 'p_feasible',
           'shot_mean_ratio', 'best_sample_energy', 'flow_before_repair',
           'flow_after_repair', 'opt_nip', 'greedy', 'maxflow',
           'ground_energy', 'offset', 'sample_time_sec', 'variables']


def donor_angles(tiny_csv=TINY_CSV):
    """{depth: angles} of the transfer donor (the rows with no transfer columns)."""
    tiny = pd.read_csv(tiny_csv, comment='#')
    donor = tiny[tiny['transfer_p_optimal'].isna()]
    if donor['instance'].nunique() != 1:
        raise ValueError(f'{tiny_csv}: expected one donor instance')
    return {int(row.reps): json.loads(row.theta) for row in donor.itertuples()}


def rounded(value):
    if isinstance(value, float) and math.isfinite(value):
        return round(value, 6)
    return '' if isinstance(value, float) else value


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    parser.add_argument('--manifest', default=MANIFEST)
    parser.add_argument('--reps', type=lambda s: [int(p) for p in s.split(',')],
                        default=[1, 2, 3])
    parser.add_argument('--angles', default='donor',
                        help=f'comma-separated, from {ANGLE_SOURCES}')
    parser.add_argument('--bond-dimension', type=int, default=32)
    parser.add_argument('--train-max-qubits', type=int, default=81,
                        help='train only rows up to this many qubits')
    parser.add_argument('--train-maxiter', type=int, default=100)
    parser.add_argument('--shots', type=int, default=4096)
    parser.add_argument('--seed', type=int, default=0)
    parser.add_argument('--only', help='comma-separated instance basenames')
    parser.add_argument('--out', required=True)
    args = parser.parse_args(argv)
    sources = args.angles.split(',')
    if not set(sources) <= set(ANGLE_SOURCES):
        parser.error(f'--angles must be from {ANGLE_SOURCES}')

    import qaoa_qiskit  # needs requirements-qaoa.txt

    commit = rb.repo_commit()
    donor = donor_angles()
    manifest = pd.read_csv(args.manifest, comment='#')
    if args.only:
        keep = set(args.only.split(','))
        manifest = manifest[manifest['instance'].map(os.path.basename).isin(keep)]
    with open(args.out, 'w', newline='') as handle:
        handle.write('# Generated by run_qaoa_mid.py -- see its docstring.\n')
        handle.write(f"# command: {' '.join(sys.argv)}\n")
        handle.write(f'# repo commit: {commit}\n')
        handle.write(f'# Aer matrix_product_state, bond dimension '
                     f'{args.bond_dimension}; {args.shots} shots, seed '
                     f'{args.seed}; donor angles from {TINY_CSV}\n')
        handle.write(f'# versions: networkx {version("networkx")}, '
                     f'qiskit {version("qiskit")}, qiskit-aer {version("qiskit-aer")}; '
                     'qubit order recorded in each row as variables\n')
        writer = csv.DictWriter(handle, fieldnames=COLUMNS)
        writer.writeheader()
        handle.flush()
        for row in manifest.itertuples():
            problem = qc.build_problem(row.instance, int(row.B), max_qubits=10_000,
                                       exact_backend='gurobi', order='rcm')
            for reps in args.reps:
                backend = qaoa_qiskit.QiskitBackend(
                    problem, reps, method='mps',
                    max_bond_dimension=args.bond_dimension)
                for source in sources:
                    if source == 'train' and (
                            problem.num_qubits > args.train_max_qubits):
                        continue
                    theta = donor[reps] if source == 'donor' else None
                    result = qc.run_qaoa(backend, problem, reps,
                                         shots=args.shots, seed=args.seed,
                                         maxiter=args.train_maxiter,
                                         theta=theta)
                    out = {column: rounded(getattr(result, column))
                           for column in COLUMNS if hasattr(result, column)}
                    out.update({
                        'instance': row.instance, 'family': row.family,
                        'qubits': problem.num_qubits, 'angles': source,
                        'bond_dimension': args.bond_dimension,
                        'theta': json.dumps([round(t, 6) for t in result.theta]),
                        'maxflow': problem.maxflow,
                        'ground_energy': problem.ground_energy,
                        'offset': problem.offset,
                        'variables': json.dumps(problem.variables),
                    })
                    writer.writerow(out)
                    handle.flush()
                    print(f'{row.instance} B={row.B} p={reps} {source}: '
                          f'gap closed {result.gap_closed:.3f}, P(optimal) '
                          f'{result.shot_p_optimal:.3f}, flow ratio '
                          f'{result.shot_mean_ratio:.3f} '
                          f'({result.train_time_sec + result.sample_time_sec:.0f} s)',
                          flush=True)
    return 0


if __name__ == '__main__':
    sys.exit(main())
